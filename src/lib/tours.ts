export function tourBySlug(slug: string) {
  return TOURS.find((tour) => tour.slug === slug);
}

export function toursByCategory(category: Category) {
  return TOURS.filter((tour) => tour.category === category);
}

export const POPULAR_TOURS = TOURS.filter((tour) => tour.popular);

/** Tours uit dezelfde categorie (aangevuld met andere) voor onder aan een tourpagina. */
export function relatedTours(tour: Tour, count = 3) {
  const sameCategory = TOURS.filter(
    (t) => t.slug !== tour.slug && t.category === tour.category,
  );
  const others = TOURS.filter(
    (t) => t.slug !== tour.slug && t.category !== tour.category,
  );
  return [...sameCategory, ...others].slice(0, count);
}
