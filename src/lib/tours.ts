export const NIET_INBEGREPEN_AUTO = [
  "Entreegelden (Edi noemt de bedragen vooraf)",
  "Maaltijden en drankjes",
  "Fooien, naar eigen inzicht",
];

export function inbegrepenVan(tour: Tour) {
  return tour.inbegrepen ?? INBEGREPEN_AUTO;
}

export function nietInbegrepenVan(tour: Tour) {
  return tour.nietInbegrepen ?? NIET_INBEGREPEN_AUTO;
}

export function formatPrice(tour: Tour) {
  const amount = `€ ${tour.priceFrom}`;
  return tour.priceUnit === "auto" ? `${amount} per auto` : `${amount} p.p.`;
}

